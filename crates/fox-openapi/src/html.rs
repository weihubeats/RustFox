#[cfg(test)]
mod tests {
    use super::*;
    use chrono::Utc;
    use fox_core::model::{EndpointStatus, HttpMethod, RequestSpec};

    fn sample() -> Endpoint {
        Endpoint {
            id: Uuid::new_v4(),
            project_id: Uuid::new_v4(),
            folder_id: None,
            name: "查询用户 <v2>".into(),
            method: HttpMethod::GET,
            path: "/api/v1/users/{id}".into(),
            description: "分页查询 & 过滤".into(),
            status: EndpointStatus::Released,
            sort_order: 0,
            request: RequestSpec {
                params: vec![KeyValue {
                    key: "page".into(),
                    value: "1".into(),
                    enabled: true,
                    description: "页码".into(),
                    field_type: Default::default(),
                    required: true,
                    example: String::new(),
                }],
                ..RequestSpec::default()
            },
            created_at: Utc::now(),
            updated_at: Utc::now(),
        }
    }

    #[test]
    fn html_contains_escaped_cards() {
        let mut examples = HashMap::new();
        let ep = sample();
        examples.insert(
            ep.id,
            vec![ResponseExample {
                id: Uuid::new_v4(),
                endpoint_id: ep.id,
                name: "成功".into(),
                status: 200,
                headers: Default::default(),
                body: "{\"ok\":true}".into(),
                content_type: "application/json".into(),
                created_at: Utc::now(),
                updated_at: Utc::now(),
            }],
        );

        let html = export_html("演示&项目", &[ep], &examples);
        assert!(html.contains("<!DOCTYPE html>"));
        assert!(html.contains("演示&amp;项目")); // 标题转义
        assert!(html.contains("查询用户 &lt;v2&gt;"));
        assert!(html.contains("分页查询 &amp; 过滤"));
        assert!(html.contains("<code>page</code>"));
        // 引号被转义为 &quot;（escape 后的 JSON 文本）
        assert!(html.contains("{&quot;ok&quot;:true}"));
        assert!(html.contains("m-get"));
        // 无脚本：纯静态离线文档
        assert!(!html.contains("<script"));
    }

    #[test]
    fn disabled_params_excluded() {
        let mut ep = sample();
        ep.request.params[0].enabled = false;
        let html = export_html("P", &[ep], &HashMap::new());
        assert!(!html.contains(">page<"));
    }
}
