//! HTML 离线单页文档导出。
//!
//! 生成零依赖的静态单文件（内联样式、无脚本）：深色主题卡片式排版，
//! 每个接口一张卡（Method 徽标 + 路径 + 描述 + 参数表 + Body / 响应示例），
//! 可直接发给前端 / 测试同学离线浏览。

use std::collections::HashMap;
use std::fmt::Write as _;

use uuid::Uuid;

use fox_core::model::{AuthSpec, BodySpec, Endpoint, KeyValue, ResponseExample};

/// 将一组接口导出为离线 HTML 文档。
pub fn export_html(
    project_name: &str,
    endpoints: &[Endpoint],
    examples_by_endpoint: &HashMap<Uuid, Vec<ResponseExample>>,
) -> String {
    let mut cards = String::with_capacity(8192);
    for (idx, ep) in endpoints.iter().enumerate() {
        let empty: Vec<ResponseExample> = Vec::new();
        let examples = examples_by_endpoint.get(&ep.id).unwrap_or(&empty);
        let _ = write_card(&mut cards, idx + 1, ep, examples);
    }

    format!(
        "<!DOCTYPE html>\n<html lang=\"zh-CN\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>{project_name} · API 文档</title>\n<style>{CSS}</style>\n</head>\n<body>\n\
         <header class=\"page-head\"><h1>{project_name}</h1>\
         <p class=\"meta\">API 文档 · 由 RustFox 导出 · 共 {count} 个接口</p></header>\n\
         <main>{cards}</main>\n\
         <footer class=\"page-foot\">Generated by RustFox</footer>\n\
         </body>\n</html>\n",
        project_name = escape(project_name),
        count = endpoints.len(),
        cards = cards,
        CSS = CSS,
    )
}

/// 拼写单个接口卡片。
fn write_card(
    out: &mut String,
    index: usize,
    ep: &Endpoint,
    examples: &[ResponseExample],
) -> std::fmt::Result {
    let method = ep.method.as_str().to_lowercase();
    let title = if ep.name.is_empty() {
        "未命名接口".to_string()
    } else {
        escape(&ep.name)
    };
    writeln!(
        out,
        "<section class=\"card\">\
         <div class=\"card-head\"><span class=\"method m-{method}\">{}</span>\
         <code class=\"path\">{}</code><h2>{title}</h2><span class=\"idx\">#{index}</span></div>",
        escape(ep.method.as_str()),
        escape(&ep.path),
        method = method,
        index = index,
    )?;

    if !ep.description.is_empty() {
        writeln!(out, "<p class=\"desc\">{}</p>", escape(&ep.description))?;
    }

    let auth = auth_line(&ep.request.auth);
    if !auth.is_empty() {
        write!(out, "<p class=\"kv-line\"><b>认证</b>{auth}</p>")?;
    }

    kv_table(out, "Query 参数", &ep.request.params)?;
    kv_table(out, "请求头", &ep.request.headers)?;

    match &ep.request.body {
        BodySpec::Json { raw } if !raw.trim().is_empty() => {
            block(out, "请求 Body (JSON)", raw)?;
        }
        BodySpec::Text { raw } if !raw.trim().is_empty() => block(out, "请求 Body (Text)", raw)?,
        BodySpec::UrlEncoded { fields } => kv_table(out, "请求 Body (Form)", fields)?,
        _ => {}
    }

    for ex in examples {
        let label = format!("响应示例 {} {}", ex.status, escape(&ex.name));
        block(out, &label, &ex.body)?;
    }

    writeln!(out, "</section>")
}

fn kv_table(out: &mut String, title: &str, list: &[KeyValue]) -> std::fmt::Result {
    let rows: Vec<&KeyValue> = list
        .iter()
        .filter(|kv| kv.enabled && !kv.key.trim().is_empty())
        .collect();
    if rows.is_empty() {
        return Ok(());
    }
    writeln!(
        out,
        "<h3>{title}</h3><table><thead><tr><th>名称</th><th>值 / 示例</th><th>说明</th></tr></thead><tbody>"
    )?;
    for kv in rows {
        let value = if kv.example.is_empty() {
            &kv.value
        } else {
            &kv.example
        };
        writeln!(
            out,
            "<tr><td><code>{}</code></td><td><code>{}</code></td><td>{}</td></tr>",
            escape(&kv.key),
            escape(value),
            escape(&kv.description),
        )?;
    }
    writeln!(out, "</tbody></table>")
}

fn block(out: &mut String, title: &str, body: &str) -> std::fmt::Result {
    writeln!(out, "<h3>{}</h3><pre>{}</pre>", escape(title), escape(body))
}

fn auth_line(auth: &AuthSpec) -> String {
    match auth {
        AuthSpec::None => String::new(),
        AuthSpec::Bearer { .. } => "Bearer Token（Authorization 头）".into(),
        AuthSpec::Basic { .. } => "Basic Auth".into(),
        AuthSpec::ApiKey { key, location, .. } => {
            format!(
                "API Key：{key}（{}）",
                if *location == fox_core::model::ApiKeyLocation::Header {
                    "Header"
                } else {
                    "Query"
                }
            )
        }
        AuthSpec::OAuth2 { .. } => "OAuth2".into(),
        AuthSpec::Digest { .. } => "Digest 认证（RFC 7616）".into(),
        AuthSpec::Hawk { .. } => "Hawk 认证（HMAC-SHA-256）".into(),
        AuthSpec::AwsV4 { .. } => "AWS Signature V4".into(),
        AuthSpec::Hmac { .. } => "HMAC (AK-SK)".into(),
        AuthSpec::DynamicSignature { config } => {
            format!(
                "动态签名：Key {}，{:?}/{:?}，签名头 {}",
                config.app_key, config.algorithm, config.encoding, config.sig_header
            )
        }
    }
}

/// 极简 HTML 转义（文档内容均来自用户数据）。
fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

